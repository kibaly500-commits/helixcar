import assert from 'node:assert/strict';
import E from '../assets/remuneration-estimation.js';
const leg={km:250,minutes:150,motorwayFastest:true,tollEuros:20};
assert.equal(E.proposedLabor(20,'idf'),45);
assert.equal(E.proposedLabor(125,'idf'),106.25);
assert.equal(E.proposedLabor(125,'hors_idf'),126.25);
assert.equal(E.proposedLabor(250,'hors_idf'),182);
assert.throws(()=>E.proposedLabor(30,'region_inconnue'),/Zone/);
assert.throws(()=>E.proposedLabor(-1,'idf'),/invalide/);
let r=E.quoteMission({zone:'hors_idf',guardDays:4,legs:[leg],fuelPricePerLiter:1.85,consumptionLitersPer100Km:6.5,clientAmountEuros:500});
assert.equal(r.internalBreakdown.workPayEuros,182);
assert.equal(r.internalBreakdown.guardEuros,40);
assert.equal(r.internalBreakdown.fuelEuros,30.06);
assert.equal(r.feesEuros,50.06);
assert.equal(r.totalEuros,272.06);
assert.equal(r.remainingBeforeCostsEuros,227.94);
assert.deepEqual(E.partnerProjection(r),{totalEuros:272.06,roadFeesIncludedEuros:50.06});
assert.ok(!JSON.stringify(E.partnerProjection(r)).includes('guard'));
r=E.quoteMission({zone:'idf',guardDays:2,legs:[{km:20,minutes:35,motorwayFastest:true}],clientAmountEuros:200});
assert.equal(r.totalEuros,65);assert.equal(r.feesEuros,0);
assert.equal(r.remainingBeforeCostsEuros,135);
r=E.quoteMission({zone:'hors_idf',guardDays:0,legs:[{...leg,tollEuros:null}],fuelPricePerLiter:1.85,consumptionLitersPer100Km:6.5});
assert.equal(r.totalEuros,null);assert.equal(E.partnerProjection(r),null);
assert.throws(()=>E.quoteMission({zone:'idf',guardDays:1,legs:[{km:20,minutes:35,motorwayFastest:false}]}),/autoroutier/);
assert.throws(()=>E.quoteMission({zone:'idf',guardDays:2.5,legs:[{km:20,minutes:35,motorwayFastest:true}]}),/entier/);
assert.throws(()=>E.quoteMission({zone:'idf',guardDays:0,legs:[{km:20,minutes:35,motorwayFastest:true}],consumptionLitersPer100Km:6}),/carburant/);
const p={idf:{minimum:10,base:10,tiers:[{upTo:Infinity,rate:1}]},hors_idf:{minimum:20,base:20,tiers:[{upTo:Infinity,rate:2}]}};
assert.equal(E.proposedLabor(20,'idf',p),30);
assert.equal(E.proposedLabor(20,'hors_idf',p),60);
