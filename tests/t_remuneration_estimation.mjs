import assert from 'node:assert/strict';
import E from '../assets/remuneration-estimation.js';
const base={workPayEuros:100,guardDays:4,fuelPricePerLiter:1.85,consumptionLitersPer100Km:6.5,legs:[{km:250,minutes:150,motorwayFastest:true,tollEuros:20}]};
let x=E.estimate(base);
assert.equal(x.status,'estimation_complete');
assert.equal(x.internalBreakdown.guardEuros,40);
assert.equal(x.internalBreakdown.fuelEuros,30.06);
assert.equal(x.feesEuros,50.06);assert.equal(x.totalEuros,190.06);
assert.deepEqual(E.partnerProjection(x),{totalEuros:190.06,roadFeesIncludedEuros:50.06});
assert.ok(!JSON.stringify(E.partnerProjection(x)).includes('guard'));
x=E.estimate({...base,legs:[{...base.legs[0],tollEuros:null}]});
assert.equal(x.status,'peages_a_verifier');assert.equal(x.totalEuros,null);assert.equal(E.partnerProjection(x),null);
assert.deepEqual(x.missingTollLegs,[1]);
assert.throws(()=>E.estimate({...base,legs:[{...base.legs[0],motorwayFastest:false}]}),/autoroutier/);
assert.throws(()=>E.estimate({...base,guardDays:-1}),/invalide/);
assert.throws(()=>E.estimate({...base,legs:[{...base.legs[0],km:NaN}]}),/invalide/);
x=E.estimate({...base,guardDays:0,legs:[{...base.legs[0],km:0,minutes:0,tollEuros:0}]});
assert.equal(x.totalEuros,100);
console.log('PASS rémunération : garde 10 €/jour, essence, péages, inconnus bloquants, trajet autoroutier, données partenaire minimales.');
