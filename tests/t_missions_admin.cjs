const assert=require('node:assert/strict');
const {etape,datesCiviles,debutDepasse,typePrestation,motifHistorique}=require('../assets/missions-admin.js');
const published={publiee_le:'2026-11-01',statut:'a_pourvoir'};
assert.equal(etape({statut:'brouillon'},null,false),'preparer');
assert.equal(etape({statut:'en_attente'},{statut:'brouillon'},false),'preparer');
assert.equal(etape({statut:'en_attente'},published,false),'attribuer');
assert.equal(etape({statut:'proposee',convoyeur_id:'a'},null,false),'attribuer');
assert.equal(etape({statut:'acceptee',convoyeur_id:'a'},published,false),'avenir');
assert.equal(etape({statut:'en_cours',convoyeur_id:'a'},published,true),'historique');
assert.equal(etape({statut:'fini',convoyeur_id:'a'},published,true),'historique');
assert.equal(etape({statut:'terminee',convoyeur_id:'a'},published,false),'historique');
assert.equal(etape({statut:'annulee'},published,false),'historique');
assert.equal(etape({statut:'en_attente'},published,true),'historique');
const fleet=[{statut:'brouillon'},{statut:'en_attente'},{statut:'acceptee',convoyeur_id:'a'}];
assert.deepEqual(fleet.map((m,i)=>etape(m,i?published:null,false)),['preparer','attribuer','avenir']);
console.log('PASS missions exclusives par étape, proposition non acceptée, dates prioritaires, archives et flotte partiellement attribuée');

assert.equal(datesCiviles({date_livraison:null},'2026-11-09').date_livraison,'2026-11-09');
assert.equal(datesCiviles({date_livraison:'2026-11-09T18:15:00.000000'}).date_livraison,'2026-11-09T18:15:00');

const now=new Date('2026-11-11T15:00:00Z');
assert.equal(debutDepasse({date_prise_en_charge:'2026-07-22 11:00:45.745'},now),true);
assert.equal(debutDepasse({date_intervention:'2026-11-10',date_fin_intervention:'2026-11-20'},now),true);
assert.equal(debutDepasse({date_intervention:'2026-11-11'},now),false);
assert.equal(debutDepasse({date_intervention:'2026-11-11',heure_debut_intervention:'15:30'},now),true);
assert.equal(debutDepasse({date_prise_en_charge:'2026-11-25 18:15:00'},now),false);
assert.equal(debutDepasse({date_prise_en_charge:'2026-11-11T16:30:00+01:00'},now),false);
assert.equal(debutDepasse({},now),false);
assert.equal(typePrestation({type_mission:'convoyage'},{type_service:'stockage'}),'convoyage');
assert.equal(typePrestation({type_mission:'nettoyage'},{type_service:'convoyage'}),'nettoyage');
assert.equal(typePrestation({},{type_service:'nettoyage'}),'nettoyage');
assert.equal(typePrestation({}), 'inconnu');
assert.match(motifHistorique({statut:'en_cours',convoyeur_id:'a'}),/réalisation non validée/);
assert.match(motifHistorique({statut:'brouillon'}),/Sans partenaire/);
assert.match(motifHistorique({statut:'terminee'}),/Terminée et validée/);
assert.match(motifHistorique({statut:'fini'}),/validation en attente/);
console.log('PASS dates Paris, début passé, dates manquantes, type réel et motifs sans validation fictive');
